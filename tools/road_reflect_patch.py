# The wet roads' reflections of the scene (local change, pgr4 project): every road pixel shader
# (psSceneRoadSurfaceGotham4 and its _NIGHT variants) that reads the lights' halo (tf13: the
# game's wet road reflection, its lights' sprites blurred at 320x180 and read mirrored on the
# screen), translated by ucode2hlsl.py from the shader dump (work\shaders\<hash>.ps.txt), each read
# of tf13 going through XeRoadReflect (shaders/road_reflect_hooks.hlsli), written to
# pgr4\shaders\<hash>.ps.hlsl; and the list of their hashes for the renderer
# (pgr4-native/src/native/road_reflect_list.h: the draws that get the scene's copy).
#   py road_reflect_patch.py
import os
import re
import subprocess
import sys

ROOT = r'D:\Apps\PGR4'
NAMES = os.path.join(ROOT, r'pgr4\shaders\shader_names.tsv')
DUMP = os.path.join(ROOT, r'work\shaders')
OUT = os.path.join(ROOT, r'pgr4\shaders')
LIST = os.path.join(ROOT, r'pgr4\pgr4-native\src\native\road_reflect_list.h')
GEN = os.path.join(ROOT, r'pgr4\tools\ucode2hlsl.py')
FETCH = re.compile(r'(TEX2D(?:_LEVEL)?\(13, float2\([^()]*\)[^;]*?\));')
# The game's wetness just before (its puddles' mask times c34.x): `{ float4 tN = XeMul(rA.aaaa,
# c34.xxxx); ... rB.b = tN.b; }`, passed to the hook as well.
WETNESS = re.compile(r'\{ float4 (t\d+) = XeMul\((r\d+)\.([xyzw])\3\3\3, c34\.xxxx\);[^}]*?'
                     r'(r\d+)\.([xyzw]) = \1\.\5;')


def main():
    names = {}
    for line in open(NAMES, encoding='utf-8'):
        p = line.rstrip('\n').split('\t')
        if len(p) > 2 and p[2]:
            names[p[0]] = p[2]
    done = []
    for h, n in sorted(names.items()):
        dump = os.path.join(DUMP, h + '.ps.txt')
        if not n.startswith('psSceneRoadSurface') or not os.path.exists(dump):
            continue
        if 'tf13' not in open(dump).read():
            continue
        tmp = os.path.join(OUT, h + '.gen.tmp')
        r = subprocess.run([sys.executable, GEN, dump, tmp], capture_output=True, text=True)
        if r.returncode:
            print(h, 'non traduit :', r.stderr.strip().split('\n')[-1])
            continue
        text = open(tmp).read()
        os.remove(tmp)
        fetch = FETCH.search(text)
        wetness = list(WETNESS.finditer(text, 0, fetch.start())) if fetch else []
        if not wetness:
            print(h, 'pas de mouillé avant le halo')
            continue
        w = wetness[-1]
        text, count = FETCH.subn(
            lambda m: f'XeRoadReflect({m.group(1)}, i, {w.group(4)}.{w.group(5)});', text)
        if not count:
            print(h, 'pas de lecture du halo')
            continue
        header = (f'// Wet road: variant {h} of the game\'s {n} (road_reflect_hooks.hlsli).\n'
                  '#include "road_reflect_hooks.hlsli"\n')
        open(os.path.join(OUT, h + '.ps.hlsl'), 'w').write(header + text)
        done.append(h)
    rows = ',\n'.join(f'    0x{h}ull' for h in done)
    open(LIST, 'w').write(
        '// Generated by pgr4/tools/road_reflect_patch.py (local change, pgr4 project): the road\n'
        '// pixel shaders whose replacements reflect the scene on wet roads, sorted.\n'
        '#pragma once\n\n#include <cstdint>\n\nnamespace pgr4::native {\n\n'
        f'inline constexpr uint64_t kRoadReflectShaders[] = {{\n{rows},\n}};\n\n'
        '}  // namespace pgr4::native\n')
    print(len(done), 'shaders de route')


if __name__ == '__main__':
    main()
